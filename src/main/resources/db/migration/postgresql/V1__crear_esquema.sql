-- Esquema inicial. Flyway ejecuta este script con el schema "adopcion" como schema por defecto,
-- por eso los nombres de tabla no llevan prefijo. Las restricciones replican las de las entidades JPA.

CREATE TABLE tipos_mascota (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    CONSTRAINT uk_tipo_mascota_nombre UNIQUE (nombre)
);

CREATE TABLE mascotas (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(100) NOT NULL,
    tipo_mascota_id BIGINT       NOT NULL,
    edad            INTEGER      NOT NULL,
    disponible      BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_mascota_edad CHECK (edad >= 0),
    CONSTRAINT fk_mascota_tipo_mascota FOREIGN KEY (tipo_mascota_id) REFERENCES tipos_mascota (id)
);

CREATE TABLE usuarios (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre             VARCHAR(100) NOT NULL,
    correo_electronico VARCHAR(150) NOT NULL,
    telefono           VARCHAR(20)  NOT NULL,
    CONSTRAINT uk_usuario_correo UNIQUE (correo_electronico)
);

CREATE TABLE adopciones (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mascota_id     BIGINT NOT NULL,
    usuario_id     BIGINT NOT NULL,
    fecha_adopcion DATE   NOT NULL,
    CONSTRAINT uk_adopcion_mascota UNIQUE (mascota_id),
    CONSTRAINT fk_adopcion_mascota FOREIGN KEY (mascota_id) REFERENCES mascotas (id),
    CONSTRAINT fk_adopcion_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);

-- PostgreSQL no indexa automáticamente las claves foráneas
CREATE INDEX ix_mascotas_tipo_mascota_id ON mascotas (tipo_mascota_id);
CREATE INDEX ix_adopciones_usuario_id ON adopciones (usuario_id);
